#!/usr/bin/env python3
"""Build the unified Workbench Obsidian plugin bundle."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import sys
import tempfile
from pathlib import Path


ROOT = Path(__file__).resolve().parent
SEPARATOR = b"// ===========================================================================\n"

# Keep all imports needed by in-house modules here. Top-level CommonJS imports
# are removed from modules/*.js before those sources are concatenated.
HEADER = """/*
 * Workbench — one unified plugin plus secure operator input.
 *
 *   1. VM Connect               (our code)
 *   2. Countdown Bar            (our code)
 *   3. Excalidraw Live Text     (our code)
 *   4. internetvin Terminal     (third-party, Vin Verma, MIT)
 *   5. Workbench            (third-party, modified by us)
 *   6. Secure Input             (our code)
 *   7. Codex Attention          (our code)
 *
 * This file is AUTO-GENERATED by build.py. Do not edit directly —
 * edit files in modules/ or vendor/ and rerun `python3 build.py`.
 *
 * Vendor plugin bundles are wrapped in IIFEs so their internal helpers
 * (__commonJS, __export, main_exports, etc.) don't collide.
 */

const { Plugin, PluginSettingTab, Setting, Notice, Menu, FuzzySuggestModal, Modal } = require('obsidian');
const { exec, execFile, spawn } = require('child_process');
const fs = require('fs');
const path = require('path');
const os = require('os');

// Vendor plugin class holders — declared BEFORE vendor IIFEs so the
// assignment inside each IIFE goes to these top-level vars (not an
// accidental undeclared global) and isn't later clobbered by a re-init.
var __TerminalPluginClass = null;
var __GSDPluginClass = null;

""".encode("utf-8")

TOP_LEVEL_REQUIRE_RE = re.compile(
    rb"^const [^\n]+ = require\([^\n]+\);\n", re.MULTILINE
)


class BuildError(RuntimeError):
    """Raised when source shape drift would make the bundle ambiguous."""


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def replace_exact(
    source: bytes, old: bytes, new: bytes, expected_count: int, source_name: str
) -> bytes:
    actual_count = source.count(old)
    if actual_count != expected_count:
        raise BuildError(
            f"{source_name}: expected {expected_count} occurrence(s) of "
            f"{old!r}, found {actual_count}"
        )
    return source.replace(old, new)


def module_source(
    relative_path: str,
    export_name: str,
    expected_imports: int,
    replacements: tuple[tuple[bytes, bytes, int], ...] = (),
) -> bytes:
    path = ROOT / relative_path
    source = path.read_bytes()

    source, import_count = TOP_LEVEL_REQUIRE_RE.subn(b"", source)
    if import_count != expected_imports:
        raise BuildError(
            f"{relative_path}: expected {expected_imports} top-level require line(s), "
            f"found {import_count}"
        )

    export_line = f"module.exports = {export_name};\n".encode()
    source = replace_exact(source, export_line, b"", 1, relative_path)

    for old, new, expected_count in replacements:
        source = replace_exact(source, old, new, expected_count, relative_path)

    return source


def section_marker(kind: str, name: str, *, blank_after: bool) -> bytes:
    label = f"// {kind}" + (f": {name}" if name else "") + "\n"
    marker = (
        b"\n"
        + SEPARATOR
        + label.encode("utf-8")
        + SEPARATOR
    )
    return marker + (b"\n" if blank_after else b"")


def vendor_section(name: str, holder: str, relative_path: str) -> bytes:
    source = (ROOT / relative_path).read_bytes()
    if relative_path == "vendor/internetvin-terminal/main.js":
        source = replace_exact(source, b"__WORKBENCH_PTY_SOURCE__",
                               json.dumps((ROOT / "pty-helper.py").read_text()).encode(), 1, relative_path)
    if not source.endswith(b"\n"):
        raise BuildError(f"{relative_path}: vendor source must end with a newline")

    prefix = (
        f"{holder} = (function () {{\n"
        "  var module = { exports: {} };\n"
        "  var exports = module.exports;\n"
    ).encode("utf-8")
    suffix = (
        b"\n"
        b"  var __mod = module.exports;\n"
        b"  return (__mod && __mod.default) ? __mod.default : __mod;\n"
        b"})();\n\n"
    )
    return (
        section_marker("Vendor bundle", name, blank_after=False)
        + prefix
        + source
        + suffix
    )


def render() -> bytes:
    vm_connect = module_source(
        "modules/vm-connect.js",
        "VMConnectModule",
        5,
        (
            (b"GSD Control's picker", b"Workbench's picker", 2),
            (b"the GSD picker are named", b"the workspace picker are named", 1),
        ),
    )
    countdown = module_source(
        "modules/countdown.js",
        "CountdownModule",
        1,
        ((b"DEFAULT_SETTINGS", b"COUNTDOWN_DEFAULT_SETTINGS", 4),),
    )
    excalidraw = module_source(
        "modules/excalidraw-live-text.js",
        "ExcalidrawLiveTextModule",
        1,
    )
    secure_input = module_source(
        "modules/secure-input.js",
        "SecureInputModule",
        0,
    )
    codex_attention = module_source(
        "modules/codex-attention.js",
        "CodexAttentionModule",
        0,
    )
    orchestrator = (ROOT / "modules/orchestrator.js").read_bytes()
    if not orchestrator.endswith(b"\n"):
        raise BuildError("modules/orchestrator.js: source must end with a newline")

    return b"".join(
        (
            HEADER,
            section_marker("Module", "VMConnectModule", blank_after=True),
            vm_connect,
            section_marker("Module", "CountdownModule", blank_after=True),
            countdown,
            section_marker("Module", "ExcalidrawLiveTextModule", blank_after=True),
            excalidraw,
            section_marker("Module", "SecureInputModule", blank_after=True),
            secure_input,
            section_marker("Module", "CodexAttentionModule", blank_after=True),
            codex_attention,
            vendor_section(
                "internetvin-terminal",
                "__TerminalPluginClass",
                "vendor/internetvin-terminal/main.js",
            ),
            vendor_section(
                "gsd-control", "__GSDPluginClass", "vendor/gsd-control/main.js"
            ),
            section_marker(
                "Orchestrator — Workbench Plugin class",
                "",
                blank_after=True,
            ),
            orchestrator,
        )
    )


def resolve_output(value: str) -> Path:
    output = Path(value).expanduser()
    return output if output.is_absolute() else ROOT / output


def write_atomic(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    mode = path.stat().st_mode & 0o777 if path.exists() else 0o644
    temporary_name: str | None = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="wb", prefix=f".{path.name}.", dir=path.parent, delete=False
        ) as temporary:
            temporary_name = temporary.name
            temporary.write(data)
            temporary.flush()
            os.fsync(temporary.fileno())
        os.chmod(temporary_name, mode)
        os.replace(temporary_name, path)
        temporary_name = None
    finally:
        if temporary_name is not None:
            Path(temporary_name).unlink(missing_ok=True)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify that the output already matches the canonical sources",
    )
    parser.add_argument(
        "--output",
        default="main.js",
        help="output path, relative to the plugin root by default",
    )
    args = parser.parse_args(argv)

    try:
        bundle = render()
    except (BuildError, OSError) as error:
        print(f"build failed: {error}", file=sys.stderr)
        return 1

    output = resolve_output(args.output)
    if args.check:
        try:
            existing = output.read_bytes()
        except FileNotFoundError:
            print(f"build check failed: {output} does not exist", file=sys.stderr)
            return 1
        if existing != bundle:
            print(
                "build check failed: bundle is stale\n"
                f"  expected: {len(bundle)} bytes sha256={sha256(bundle)}\n"
                f"  existing: {len(existing)} bytes sha256={sha256(existing)}",
                file=sys.stderr,
            )
            return 1
        print(f"build check passed: {output} ({len(bundle)} bytes, sha256={sha256(bundle)})")
        return 0

    write_atomic(output, bundle)
    print(f"built {output} ({len(bundle)} bytes, sha256={sha256(bundle)})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
